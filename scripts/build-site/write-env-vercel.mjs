// Write .env.vercel (gitignored, 0600): every environment variable the hosted deployment
// needs, for the owner to import into the Vercel project. Values come from .env.local, the
// hosted Devnet wallet file and fresh random secrets; NOTHING is printed except names.
// Re-running keeps AXP_STATE_KEY and CRON_SECRET (changing the state key would make
// stored runs unreadable). Also writes .env.vercel.public-names.txt (names only).
import {readFileSync,writeFileSync,existsSync,chmodSync} from 'node:fs';
import {join} from 'node:path';
import {parseEnv} from 'node:util';
import {randomBytes} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {repositoryRoot as root} from '../../packages/config/local.mjs';
import {loadWallets,walletsPath} from '../../packages/hosted/wallets.mjs';

const target=join(root,'.env.vercel'),names=join(root,'.env.vercel.public-names.txt');
for(const f of [target,names]){const r=spawnSync('git',['check-ignore','-q',f],{cwd:root});if(r.status!==0)throw new Error(`${f} is not gitignored; refusing to write`);}
const local=existsSync(join(root,'.env.local'))?parseEnv(readFileSync(join(root,'.env.local'),'utf8')):{};
const prior=existsSync(target)?parseEnv(readFileSync(target,'utf8')):{};
const wallets=loadWallets({},{root});// validates the 0600 wallet file
const walletsB64=Buffer.from(readFileSync(walletsPath({},root))).toString('base64');

// [name, value, secret?, purpose]
const vars=[
  ['JEV_API_KEY',local.JEV_API_KEY||local.TYPESAFE_API_KEY||'',true,'Jev (TypeSafe) decisions'],
  ['DEEPSEEK_API_KEY',local.DEEPSEEK_API_KEY||'',true,'DeepSeek deepseek-flash organic answers'],
  ['AXP_DEVNET_WALLETS',walletsB64,true,'base64 of the stable Devnet wallets (2 advertiser payers + publisher; Devnet only)'],
  ['AXP_STATE_KEY',prior.AXP_STATE_KEY||randomBytes(32).toString('base64'),true,'AES-256-GCM key for private run state at rest; keep stable'],
  ['CRON_SECRET',prior.CRON_SECRET||randomBytes(24).toString('hex'),true,'bearer secret Vercel Cron sends to /api/cron/sweep'],
  ['AXP_LIVE_PASSCODE',prior.AXP_LIVE_PASSCODE??'',true,'optional judge passcode (empty = none)'],
  ['BLOB_READ_WRITE_TOKEN','',true,'Vercel Blob (PRIVATE store) token: injected by Vercel when the store is connected; leave empty here'],
  ['AXP_LIVE_ENABLED','1',false,'1 = accept live runs'],
  ['AXP_RUN_STORE','blob',false,'run store backend: blob (Vercel Blob) | upstash'],
  ['AXP_LIVE_DAILY_CAP','20',false,'runs per UTC day'],
  ['AXP_LIVE_IP_DAILY_CAP','3',false,'runs per IP per UTC day'],
  ['AXP_LIVE_MAX_ACTIVE','1',false,'concurrent runs'],
  ['AXP_LIVE_DELIVERY_WINDOW_SECONDS','600',false,'time the browser has to acknowledge awards'],
];
const missing=vars.filter(([n,v,secret])=>secret&&!v&&!['AXP_LIVE_PASSCODE','BLOB_READ_WRITE_TOKEN'].includes(n)).map(([n])=>n);
const header=['# AXP hosted deployment environment for the Vercel project (Production).',
  '# GENERATED by scripts/build-site/write-env-vercel.mjs. Gitignored. NEVER commit or paste this file.',
  '# Values are throwaway hackathon test credentials (API keys with usage limits, Devnet-only wallets);',
  '# rotate the API keys after judging. Optional alternative store: KV_REST_API_URL + KV_REST_API_TOKEN',
  '# (Upstash) with AXP_RUN_STORE=upstash.','#',
  ...vars.map(([n,,secret,purpose])=>`# ${n} (${secret?'secret':'non-secret'}): ${purpose}`),''];
const body=vars.map(([n,v])=>`${n}=${/[\s#"'$]/.test(v)?JSON.stringify(v):v}`);
writeFileSync(target,[...header,...body,''].join('\n'),{mode:0o600});chmodSync(target,0o600);
writeFileSync(names,['# Names only (no values). Secret = owner imports from .env.vercel; non-secret = may be set via CLI.',
  '[secret]',...vars.filter(v=>v[2]).map(([n,,,p])=>`${n}  # ${p}`),'','[non-secret]',...vars.filter(v=>!v[2]).map(([n,v,,p])=>`${n}=${v}  # ${p}`),''].join('\n'),{mode:0o600});
console.log(JSON.stringify({written:['.env.vercel','.env.vercel.public-names.txt'],mode:'600',variables:vars.map(([n,v,secret])=>({name:n,secret,filled:!!v})),missing,
  walletAddresses:{payers:Object.values(wallets.payers).map(p=>p.address),publisher:wallets.publisher.address}},null,2));
